def state_legend() -> None:
    """Render a concise horizontal legend explaining the four verdict states."""
    items_html = []
    hatch_style = (
        "repeating-linear-gradient("
        "45deg, transparent, transparent 3px, "
        "rgba(138, 143, 152, 0.4) 3px, rgba(138, 143, 152, 0.4) 6px)"
    )

    for token in VERDICT_TOKENS.values():
        hatch = (
            f"background-image: {hatch_style};"
            if token.pattern == "hatched"
            else ""
        )
        items_html.append(
            f'<div class="state-legend-item">'
            f'<span style="display: inline-block; width: 14px; height: 14px; '
            f'background-color: {token.color}; border-radius: 3px; {hatch}"></span>'
            f"<span><b>{token.icon} {token.label}</b></span>"
            f"</div>"
        )

    legend_html = (
        '<div class="state-legend-container" role="region" '
        'aria-label="Verdict Legend">'
        f'{"".join(items_html)}'
        "</div>"
    )
    st.markdown(legend_html, unsafe_allow_html=True)

"""Reusable UI components for Tendency Tax Streamlit application (D6.3).

Components take plain data (floats, strings, DataFrames), contain no analysis
logic, and never recompute a verdict. All textual language is association-only.
"""

from typing import Any

import plotly.graph_objects as go
import streamlit as st

from app.data import format_ci, format_int
from app.ui.theme import (
    SERIES_COLORS,
    VERDICT_TOKENS,
    apply_template,
)


def verdict_chip(state: str, small: bool = False) -> str:
    """Return HTML markup for a verdict chip with icon and label.

    Parameters
    ----------
    state : str
        One of 'premium', 'reverse', 'none', 'cant_tell'.
    small : bool
        Whether to render a compact chip.
    """
    if state not in VERDICT_TOKENS:
        valid_keys = list(VERDICT_TOKENS.keys())
        raise ValueError(
            f"Unknown verdict state '{state}'. Must be one of {valid_keys}."
        )

    token = VERDICT_TOKENS[state]
    css_class = token.name.replace("_", "-")
    small_class = " small" if small else ""

    return (
        f'<span class="verdict-chip {css_class}{small_class}" '
        f'role="status" aria-label="{token.label}">'
        f'<span class="verdict-icon" aria-hidden="true">{token.icon}</span> '
        f"<span>{token.label}</span>"
        f"</span>"
    )


def verdict_banner(sentence: str, state: str) -> None:
    """Render a large verdict-first banner block shown at top of the test panel.

    Parameters
    ----------
    sentence : str
        Plain-language sentence generated by estimate.verdict().
    state : str
        Verdict state e.g. 'premium', 'cant_tell', 'supported', etc.
    """
    mapped_state = state
    if state == "supported":
        mapped_state = "premium"
    elif state in ("not supported / inconclusive", "not_supported", "inconclusive"):
        mapped_state = "cant_tell"

    if mapped_state not in VERDICT_TOKENS:
        mapped_state = "cant_tell"

    token = VERDICT_TOKENS[mapped_state]
    css_class = token.name.replace("_", "-")

    banner_html = (
        f'<div class="verdict-banner {css_class}" role="region" aria-label="Verdict">'
        f'<div class="verdict-banner-title" style="color: {token.color};">'
        f"<span>{token.icon}</span> <span>{token.label}</span>"
        f"</div>"
        f'<div class="verdict-banner-sentence">{sentence}</div>'
        f"</div>"
    )
    st.markdown(banner_html, unsafe_allow_html=True)


def metric_card(
    label: str,
    value: str,
    interval: tuple[float, float] | None = None,
    n: int | None = None,
    help_text: str | None = None,
) -> None:
    """Render a standard metric card with uncertainty interval and sample size.

    Parameters
    ----------
    label : str
        Display title for the metric.
    value : str
        Pre-formatted value string (e.g. from format_epa).
    interval : tuple[float, float] | None
        Optional (lo, hi) bounds for 95% confidence interval.
    n : int | None
        Optional play or game count.
    help_text : str | None
        Optional descriptive tooltip text.
    """
    sub_parts = []
    if interval is not None:
        sub_parts.append(f"95% CI {format_ci(interval[0], interval[1])}")
    if n is not None:
        sub_parts.append(f"N = {format_int(n)}")

    sub_html = (
        f'<div class="metric-card-sub">{" &bull; ".join(sub_parts)}</div>'
        if sub_parts
        else ""
    )
    help_attr = f' title="{help_text}"' if help_text else ""

    card_html = (
        f'<div class="metric-card-box"{help_attr}>'
        f'<div class="metric-card-label">{label}</div>'
        f'<div class="metric-card-value">{value}</div>'
        f"{sub_html}"
        f"</div>"
    )
    st.markdown(card_html, unsafe_allow_html=True)


def interval_plot(
    rows: list[dict[str, Any]],
    estimate_col: str = "delta",
    ci_lo_col: str = "ci_lo",
    ci_hi_col: str = "ci_hi",
    label_col: str = "label",
    n_col: str = "n_plays",
    state_col: str = "verdict",
    title: str = "Point Estimates and 95% Confidence Intervals",
    xaxis_title: str = "Delta (EPA / play)",
    zero_line: bool = True,
    height: int | None = None,
) -> go.Figure:
    """Render a horizontal point-and-interval chart on a shared axis.

    Features:
      - Uses registered 'tendency' Plotly template.
      - Dashed zero reference line.
      - Colors mapped to verdict state or series tokens.
      - Hover shows label, estimate, interval, and n.
    """
    y_labels = [r.get(label_col, f"Row {i}") for i, r in enumerate(rows)]
    estimates = [r.get(estimate_col, 0.0) for r in rows]
    ci_los = [r.get(ci_lo_col, 0.0) for r in rows]
    ci_his = [r.get(ci_hi_col, 0.0) for r in rows]
    n_vals = [r.get(n_col, None) for r in rows]
    states = [r.get(state_col, "cant_tell") for r in rows]

    errors_plus = [
        hi - est if hi is not None and est is not None else 0.0
        for est, hi in zip(estimates, ci_his, strict=False)
    ]
    errors_minus = [
        est - lo if lo is not None and est is not None else 0.0
        for est, lo in zip(estimates, ci_los, strict=False)
    ]

    colors = []
    for s in states:
        if s in VERDICT_TOKENS:
            colors.append(VERDICT_TOKENS[s].color)
        elif s in SERIES_COLORS:
            colors.append(SERIES_COLORS[s])
        else:
            colors.append(VERDICT_TOKENS["cant_tell"].color)

    customdata = []
    for lo, hi, n in zip(ci_los, ci_his, n_vals, strict=False):
        n_str = f"N = {format_int(n)}" if n is not None else ""
        ci_str = format_ci(lo, hi)
        customdata.append([ci_str, n_str])

    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=estimates,
            y=y_labels,
            mode="markers",
            marker=dict(
                size=11,
                color=colors,
            ),
            error_x=dict(
                type="data",
                symmetric=False,
                array=errors_plus,
                arrayminus=errors_minus,
                thickness=2,
                width=6,
                color="#6C757D",
            ),
            customdata=customdata,
            hovertemplate=(
                "<b>%{y}</b><br/>"
                "Estimate: %{x:.3f}<br/>"
                "95% CI: %{customdata[0]}<br/>"
                "%{customdata[1]}"
                "<extra></extra>"
            ),
        )
    )

    if zero_line:
        fig.add_vline(x=0.0, line_dash="dash", line_color="rgba(138, 143, 152, 0.7)")

    calculated_height = height or max(260, len(rows) * 38 + 90)
    fig.update_layout(
        title=title,
        xaxis_title=xaxis_title,
        yaxis=dict(autorange="reversed"),
        height=calculated_height,
        margin=dict(l=10, r=20, t=40, b=40),
    )

    return apply_template(fig)


def caveat_callout(text: str, kind: str = "info") -> None:
    """Render an uncertainty or methodological caveat callout box."""
    css_class = "warning" if kind == "warning" else "info"
    icon = "⚠️" if kind == "warning" else "ℹ️"
    callout_html = (
        f'<div class="tendency-callout {css_class}" role="note">'
        f'<div style="font-weight: 600; margin-bottom: 4px;">{icon} Note</div>'
        f"<div>{text}</div>"
        f"</div>"
    )
    st.markdown(callout_html, unsafe_allow_html=True)


def sample_size_badge(n: int, min_n: int | None = None) -> str:
    """Return HTML for a sample size badge.

    Switches to warning style when n is below min_n.
    """
    is_low = min_n is not None and n < min_n
    css_class = "sample-badge warning" if is_low else "sample-badge"
    icon = "⚠️ " if is_low else ""
    return (
        f'<span class="{css_class}">'
        f"{icon}N = {format_int(n)}"
        f"</span>"
    )


def empty_state(message: str) -> None:
    """Render a neutral empty-state placeholder container."""
    html = (
        f'<div class="empty-state-box" role="status">'
        f'<div style="font-size: 24px; margin-bottom: 8px;">◌</div>'
        f"<div>{message}</div>"
        f"</div>"
    )
    st.markdown(html, unsafe_allow_html=True)


def loading_skeleton(height: int = 120) -> None:
    """Render a shimmer loading skeleton box."""
    html = f'<div class="loading-skeleton-box" style="height: {height}px;"></div>'
    st.markdown(html, unsafe_allow_html=True)


def state_legend() -> None:
    """Render a concise horizontal legend explaining the four verdict states."""
    items_html = []
    hatch_style = (
        "repeating-linear-gradient("
        "45deg, transparent, transparent 3px, "
        "rgba(138, 143, 152, 0.4) 3px, rgba(138, 143, 152, 0.4) 6px)"
    )

    for token in VERDICT_TOKENS.values():
        hatch = (
            f"background-image: {hatch_style};"
            if token.pattern == "hatched"
            else ""
        )
        items_html.append(
            f'<div class="state-legend-item">'
            f'<span style="display: inline-block; width: 14px; height: 14px; '
            f'background-color: {token.color}; border-radius: 3px; {hatch}"></span>'
            f"<span><b>{token.icon} {token.label}</b></span>"
            f"</div>"
        )

    legend_html = (
        '<div class="state-legend-container" role="region" '
        'aria-label="Verdict Legend">'
        f'{"".join(items_html)}'
        "</div>"
    )
    st.markdown(legend_html, unsafe_allow_html=True)

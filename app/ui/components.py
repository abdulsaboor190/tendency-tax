"""Reusable UI components for Tendency Tax Streamlit application (D6.3).

Components take plain data (floats, strings, DataFrames), contain no analysis
logic, and never recompute a verdict. All textual language is association-only.
"""

import math
from typing import Any

import plotly.graph_objects as go
import streamlit as st

from app.data import format_ci, format_int
from app.ui.theme import (
    SERIES_COLORS,
    VERDICT_TOKENS,
    apply_template,
)


def verdict_chip(state: str, small: bool = False) -> str:
    """Return HTML markup for a verdict chip with icon and label.

    Parameters
    ----------
    state : str
        One of 'premium', 'reverse', 'none', 'cant_tell'.
    small : bool
        Whether to render a compact chip.
    """
    if state not in VERDICT_TOKENS:
        valid_keys = list(VERDICT_TOKENS.keys())
        raise ValueError(
            f"Unknown verdict state '{state}'. Must be one of {valid_keys}."
        )

    token = VERDICT_TOKENS[state]
    css_class = token.name.replace("_", "-")
    small_class = " small" if small else ""

    return (
        f'<span class="verdict-chip {css_class}{small_class}" '
        f'role="status" aria-label="{token.label}">'
        f'<span class="verdict-icon" aria-hidden="true">{token.icon}</span> '
        f"<span>{token.label}</span>"
        f"</span>"
    )


def verdict_banner(
    sentence: str,
    state: str,
    headline: str | None = None,
    note: str | None = None,
) -> None:
    """Render a large verdict-first banner block shown at top of the test panel.

    Parameters
    ----------
    sentence : str
        Plain-language sentence generated by estimate.verdict().
    state : str
        Verdict state e.g. 'premium', 'cant_tell', 'supported', etc.
    headline : str | None
        Optional concise headline (e.g. "Inconclusive · +0.019 EPA [CI]").
    note : str | None
        Optional second-line explanation or caveat.
    """
    mapped_state = state
    if state == "supported":
        mapped_state = "premium"
    elif state in ("not supported / inconclusive", "not_supported", "inconclusive"):
        mapped_state = "cant_tell"

    if mapped_state not in VERDICT_TOKENS:
        mapped_state = "cant_tell"

    token = VERDICT_TOKENS[mapped_state]
    css_class = token.name.replace("_", "-")
    chip = verdict_chip(mapped_state, small=True)

    header_text = headline or f"{token.icon} {token.label}"

    note_html = (
        f'<div style="margin-top: 6px; font-size: 13px; '
        f'color: var(--color-text-muted);">ℹ️ {note}</div>'
        if note
        else ""
    )

    banner_html = (
        f'<div class="verdict-banner {css_class}" role="region" aria-label="Verdict">'
        f'<div class="verdict-banner-header">'
        f'<div class="verdict-banner-title">{header_text}</div>'
        f"<div>{chip}</div>"
        f"</div>"
        f'<div class="verdict-banner-sentence">{sentence}</div>'
        f"{note_html}"
        f"</div>"
    )
    st.markdown(banner_html, unsafe_allow_html=True)


def metric_card(
    label: str,
    value: str,
    interval: tuple[float, float] | None = None,
    n: int | None = None,
    help_text: str | None = None,
) -> None:
    """Render a standard metric card with uncertainty interval and sample size.

    Parameters
    ----------
    label : str
        Display title for the metric.
    value : str
        Pre-formatted value string (e.g. from format_epa).
    interval : tuple[float, float] | None
        Optional (lo, hi) bounds for 95% confidence interval.
    n : int | None
        Optional play or game count.
    help_text : str | None
        Optional descriptive tooltip text.
    """
    sub_parts = []
    if interval is not None:
        sub_parts.append(f"95% CI {format_ci(interval[0], interval[1])}")
    if n is not None:
        sub_parts.append(f"N = {format_int(n)}")

    sub_html = (
        f'<div class="metric-card-sub">{" · ".join(sub_parts)}</div>'
        if sub_parts
        else ""
    )

    # Estimate-outside-interval guard
    outside_warning_html = ""
    if interval is not None:
        try:
            # Parse numeric value if possible (strip leading +, spaces, etc.)
            val_clean = value.replace("+", "").strip()
            numeric_val = float(val_clean)
            lo, hi = float(interval[0]), float(interval[1])
            if numeric_val < lo or numeric_val > hi:
                outside_warning_html = (
                    ' <span title="The estimate lies outside its interval; '
                    'see data notes." '
                    'style="cursor: help; font-size: 14px;" role="img" '
                    'aria-label="Warning: estimate outside interval">⚠️</span>'
                )
        except (ValueError, TypeError):
            pass

    help_attr = f' title="{help_text}"' if help_text else ""

    card_html = (
        f'<div class="metric-card-box"{help_attr}>'
        f'<div class="metric-card-label">{label}{outside_warning_html}</div>'
        f'<div class="metric-card-value">{value}</div>'
        f"{sub_html}"
        f"</div>"
    )
    st.markdown(card_html, unsafe_allow_html=True)


def interval_plot(
    rows: list[dict[str, Any]],
    estimate_col: str = "delta",
    ci_lo_col: str = "ci_lo",
    ci_hi_col: str = "ci_hi",
    label_col: str = "label",
    n_col: str = "n_plays",
    state_col: str = "verdict",
    title: str = "Point Estimates and 95% Confidence Intervals",
    xaxis_title: str = "Delta (EPA / play)",
    zero_line: bool = True,
    height: int | None = None,
) -> go.Figure:
    """Render a horizontal point-and-interval chart on a shared axis.

    Features:
      - Uses registered 'tendency' Plotly template.
      - Dashed zero reference line.
      - Colors mapped to verdict state or series tokens.
      - Supports non-testable rows with hollow markers and custom labels.
      - Dynamic symmetric x-axis range based on actual intervals present.
    """
    y_labels = [r.get(label_col, f"Row {i}") for i, r in enumerate(rows)]
    estimates = [r.get(estimate_col, None) for r in rows]
    ci_los = [r.get(ci_lo_col, None) for r in rows]
    ci_his = [r.get(ci_hi_col, None) for r in rows]
    n_vals = [r.get(n_col, None) for r in rows]
    states = [r.get(state_col, "cant_tell") for r in rows]
    custom_markers = [r.get("marker_symbol", "circle") for r in rows]
    custom_line_colors = [r.get("marker_line_color", None) for r in rows]
    custom_line_widths = [r.get("marker_line_width", 0) for r in rows]

    x_scatter: list[float] = []
    errors_plus: list[float] = []
    errors_minus: list[float] = []
    colors: list[str] = []
    marker_symbols: list[str] = []
    marker_line_colors: list[str] = []
    marker_line_widths: list[int] = []
    customdata: list[list[str]] = []

    valid_bounds: list[float] = []

    for i, r in enumerate(rows):
        est = estimates[i]
        lo = ci_los[i]
        hi = ci_his[i]
        n = n_vals[i]
        s = states[i]
        sym = custom_markers[i]
        l_col = custom_line_colors[i]
        l_w = custom_line_widths[i]

        if s in VERDICT_TOKENS:
            col = VERDICT_TOKENS[s].color
        elif s in SERIES_COLORS:
            col = SERIES_COLORS[s]
        else:
            col = VERDICT_TOKENS["cant_tell"].color

        if est is not None and not math.isnan(est):
            x_scatter.append(float(est))
            valid_bounds.append(float(est))
            e_plus = hi - est if (hi is not None and not math.isnan(hi)) else 0.0
            e_minus = est - lo if (lo is not None and not math.isnan(lo)) else 0.0
            if hi is not None and not math.isnan(hi):
                valid_bounds.append(float(hi))
            if lo is not None and not math.isnan(lo):
                valid_bounds.append(float(lo))

            errors_plus.append(max(0.0, e_plus))
            errors_minus.append(max(0.0, e_minus))
            colors.append(col)
            marker_symbols.append(sym)
            marker_line_colors.append(l_col or col)
            marker_line_widths.append(l_w)

            n_str = f"N = {format_int(n)}" if n is not None else ""
            ci_str = format_ci(lo, hi)
            customdata.append([f"{est:.3f}", ci_str, n_str])
        else:
            # Non-testable row: hollow marker at 0.0 with specific label
            x_scatter.append(0.0)
            errors_plus.append(0.0)
            errors_minus.append(0.0)
            colors.append("rgba(0,0,0,0)")  # Hollow fill
            marker_symbols.append("circle")
            marker_line_colors.append("#8A8F98")
            marker_line_widths.append(2)
            n_str = f"n={n}" if n is not None else "n=0"
            custom_note = r.get("custom_text", f"not testable ({n_str})")
            customdata.append(["—", custom_note, ""])

    fig = go.Figure()
    fig.add_trace(
        go.Scatter(
            x=x_scatter,
            y=y_labels,
            mode="markers",
            marker=dict(
                size=11,
                color=colors,
                symbol=marker_symbols,
                line=dict(color=marker_line_colors, width=marker_line_widths),
            ),
            error_x=dict(
                type="data",
                symmetric=False,
                array=errors_plus,
                arrayminus=errors_minus,
                thickness=2,
                width=6,
                color="#6C757D",
            ),
            customdata=customdata,
            hovertemplate=(
                "<b>%{y}</b><br/>"
                "Estimate: %{customdata[0]}<br/>"
                "%{customdata[1]}<br/>"
                "%{customdata[2]}"
                "<extra></extra>"
            ),
        )
    )

    if zero_line:
        fig.add_vline(x=0.0, line_dash="dash", line_color="rgba(138, 143, 152, 0.7)")

    # Symmetric x-axis range based on actual intervals present
    xaxis_kwargs: dict[str, Any] = {"title": xaxis_title}
    if valid_bounds:
        max_abs = max(abs(b) for b in valid_bounds)
        pad = max(0.04, max_abs * 0.15)
        xaxis_kwargs["range"] = [-(max_abs + pad), max_abs + pad]

    calculated_height = height or max(260, len(rows) * 38 + 90)
    fig.update_layout(
        title=title,
        xaxis=xaxis_kwargs,
        yaxis=dict(autorange="reversed"),
        height=calculated_height,
        margin=dict(l=10, r=20, t=40, b=40),
    )

    return apply_template(fig)


def caveat_callout(text: str, kind: str = "info") -> None:
    """Render an uncertainty or methodological caveat callout box."""
    css_class = "warning" if kind == "warning" else "info"
    icon = "⚠️" if kind == "warning" else "ℹ️"
    callout_html = (
        f'<div class="tendency-callout {css_class}" role="note">'
        f'<div style="font-weight: 600; margin-bottom: 4px;">{icon} Note</div>'
        f"<div>{text}</div>"
        f"</div>"
    )
    st.markdown(callout_html, unsafe_allow_html=True)


def sample_size_badge(n: int, min_n: int | None = None) -> str:
    """Return HTML for a sample size badge.

    Switches to warning style when n is below min_n.
    """
    is_low = min_n is not None and n < min_n
    css_class = "sample-badge warning" if is_low else "sample-badge"
    icon = "⚠️ " if is_low else ""
    return (
        f'<span class="{css_class}">'
        f"{icon}N = {format_int(n)}"
        f"</span>"
    )


